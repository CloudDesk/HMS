import { useEffect, useMemo, useState } from 'react';
import type { OpdConsultationResponse } from '../../api/opd';
import { ICD10_DIAGNOSES, type Icd10Diagnosis } from '../../data/icd10-diagnoses';

const diagnosisLine = (diagnosis: Icd10Diagnosis) => `${diagnosis.code} - ${diagnosis.name}`;

export function diagnosesFromRecord(record: Pick<OpdConsultationResponse, 'assessment' | 'diagnoses'> | null): Icd10Diagnosis[] {
  const selected = new Map<string, Icd10Diagnosis>();
  for (const diagnosis of record?.diagnoses ?? []) {
    selected.set(diagnosis.code, { code: diagnosis.code, name: diagnosis.display, category: diagnosis.codingSystem });
  }
  // Only recover lines generated by the legacy picker. Narrative mentions are not diagnoses.
  const lines = new Set((record?.assessment ?? '').split('\n').map((line) => line.trim()));
  for (const diagnosis of ICD10_DIAGNOSES) {
    if (lines.has(diagnosisLine(diagnosis)) && !selected.has(diagnosis.code)) selected.set(diagnosis.code, diagnosis);
  }
  for (const line of lines) {
    const custom = /^(DX-\d+) - (.+)$/.exec(line);
    if (custom?.[1] && custom[2] && !selected.has(custom[1])) selected.set(custom[1], { code: custom[1], name: custom[2], category: 'Clinical Diagnosis' });
  }
  return [...selected.values()];
}

export const removeDiagnosisLine = (assessment: string, diagnosis: Icd10Diagnosis) =>
  assessment.split('\n').filter((line) => line.trim() !== diagnosisLine(diagnosis)).join('\n');

export function useOpdDiagnoses(
  consultation: OpdConsultationResponse | null,
  updateAssessment: (update: (current: string) => string) => void,
) {
  const [search, setSearch] = useState('');
  const [selected, setSelected] = useState<Icd10Diagnosis[]>(() => diagnosesFromRecord(consultation));
  useEffect(() => { setSelected(diagnosesFromRecord(consultation)); }, [consultation]);
  const filtered = useMemo(() => {
    const query = search.trim().toLowerCase();
    return query ? ICD10_DIAGNOSES.filter((item) => [item.code, item.name, item.category].some((value) => value.toLowerCase().includes(query))) : ICD10_DIAGNOSES.slice(0, 8);
  }, [search]);
  return {
    search, setSearch, selected, filtered,
    // Preserve existing coding/primary/secondary metadata. The legacy picker adds narrative
    // assessment lines; structured clinical classification remains the later diagnosis workflow.
    diagnosesForSave: consultation?.diagnoses?.filter((item) => selected.some((diagnosis) => diagnosis.code === item.code)),
    add: (diagnosis: Icd10Diagnosis) => {
      if (selected.some((item) => item.code === diagnosis.code)) return;
      setSelected((items) => [...items, diagnosis]);
      updateAssessment((current) => current ? `${current}\n${diagnosisLine(diagnosis)}` : diagnosisLine(diagnosis));
    },
    remove: (code: string) => {
      const diagnosis = selected.find((item) => item.code === code);
      if (!diagnosis) return;
      setSelected((items) => items.filter((item) => item.code !== code));
      updateAssessment((current) => removeDiagnosisLine(current, diagnosis));
    },
  };
}
